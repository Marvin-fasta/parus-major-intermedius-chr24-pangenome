#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Plot indels >= a defined minimum size in the local candidate region,
together with all candidate genes in one shared gene track.

Input variants:
    TSV produced by extract_all_variants.py

Genes:
    Local-coordinate GFF3 produced by extract_local_candidate_genes.py
"""

import argparse
import csv
from collections import defaultdict

import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, Rectangle


def parse_gff_attributes(attribute_text):
    """Parse GFF3 column 9 into a dictionary."""
    attributes = {}

    for item in attribute_text.strip().split(";"):
        if "=" in item:
            key, value = item.split("=", 1)
            attributes[key] = value

    return attributes


def read_variants(filename):
    """Read all variants from the TSV generated by extract_all_variants.py."""
    variants = []

    with open(filename, encoding="utf-8") as handle:
        reader = csv.DictReader(handle, delimiter="\t")

        for row in reader:
            variants.append(
                {
                    "chrom": row["CHROM"],
                    "position": int(row["POS"]),
                    "length_difference": int(row["LENGTH_DIFFERENCE"]),
                    "variant_type": row["VARIANT_TYPE"],
                }
            )

    return variants


def read_genes(gff3_file, reference_contig):
    """Read gene and CDS records from a local-coordinate GFF3."""
    genes = {}
    cds_by_gene = defaultdict(list)

    with open(gff3_file, encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip()

            if not line or line.startswith("#"):
                continue

            fields = line.split("\t")

            if len(fields) != 9:
                continue

            (
                contig,
                source,
                feature_type,
                start,
                end,
                score,
                strand,
                phase,
                attributes,
            ) = fields

            if contig != reference_contig:
                continue

            start = int(start)
            end = int(end)

            attrs = parse_gff_attributes(attributes)
            gene_name = attrs.get("gene")

            if not gene_name:
                continue

            if feature_type == "gene":
                genes[gene_name] = {
                    "start": start,
                    "end": end,
                    "strand": strand,
                    "cds": [],
                }

            elif feature_type == "CDS":
                cds_by_gene[gene_name].append(
                    {
                        "start": start,
                        "end": end,
                    }
                )

    # Add all unique CDS coordinates to each gene.
    for gene_name, cds_list in cds_by_gene.items():
        if gene_name not in genes:
            genes[gene_name] = {
                "start": min(cds["start"] for cds in cds_list),
                "end": max(cds["end"] for cds in cds_list),
                "strand": "?",
                "cds": [],
            }

        unique_cds = {
            (cds["start"], cds["end"])
            for cds in cds_list
        }

        genes[gene_name]["cds"] = [
            {"start": start, "end": end}
            for start, end in sorted(unique_cds)
        ]

    if not genes:
        raise ValueError(
            f"No gene annotations found on {reference_contig}"
        )

    return dict(
        sorted(
            genes.items(),
            key=lambda item: item[1]["start"],
        )
    )


def aggregate_indels(indels):
    """
    Aggregate variants with identical:
      - position
      - indel length
      - indel type

    The resulting 'count' controls marker size.
    """
    grouped = defaultdict(int)

    for indel in indels:
        key = (
            indel["position"],
            indel["length_difference"],
            indel["variant_type"],
        )
        grouped[key] += 1

    aggregated = []

    for (position, length_difference, variant_type), count in grouped.items():
        aggregated.append(
            {
                "position": position,
                "length_difference": length_difference,
                "variant_type": variant_type,
                "count": count,
            }
        )

    return sorted(
        aggregated,
        key=lambda item: (
            item["position"],
            item["length_difference"],
            item["variant_type"],
        ),
    )


def marker_size(count, base_size, increment):
    """
    Matplotlib marker size is specified as area in points^2.

    Examples with base_size=55 and increment=40:
      count 1 -> 55
      count 2 -> 95
      count 3 -> 135
    """
    return base_size + (count - 1) * increment


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Plot indels with all candidate genes in a shared gene track."
        )
    )

    parser.add_argument(
        "--variants",
        required=True,
        help="TSV generated by extract_all_variants.py",
    )

    parser.add_argument(
        "--genes-gff3",
        required=True,
        help="Local-coordinate GFF3 with candidate genes.",
    )

    parser.add_argument(
        "--reference-contig",
        default="Parus_major_reference_contig1",
        help="Local reference contig name.",
    )

    parser.add_argument(
        "--region-length",
        type=int,
        default=54925,
        help="Length of the local reference region in bp.",
    )

    parser.add_argument(
        "--min-indel-size",
        type=int,
        default=5,
        help="Minimum absolute indel length in bp. Default: 5.",
    )

    parser.add_argument(
        "--output-prefix",
        default="candidate_region_indels",
        help="Output prefix for PNG and PDF.",
    )

    args = parser.parse_args()

    variants = read_variants(args.variants)

    # Keep only insertions and deletions on the local reference path
    # with absolute length >= requested threshold.
    indels = [
        variant
        for variant in variants
        if (
            variant["chrom"] == args.reference_contig
            and variant["variant_type"] in {"INS", "DEL"}
            and abs(variant["length_difference"]) >= args.min_indel_size
        )
    ]

    if not indels:
        raise ValueError(
            f"No indels >= {args.min_indel_size} bp found on "
            f"{args.reference_contig}"
        )

    genes = read_genes(
        args.genes_gff3,
        args.reference_contig,
    )

    aggregated_indels = aggregate_indels(indels)

    insertions = [
        indel
        for indel in aggregated_indels
        if indel["variant_type"] == "INS"
    ]

    deletions = [
        indel
        for indel in aggregated_indels
        if indel["variant_type"] == "DEL"
    ]

    max_indel_length = max(
        abs(indel["length_difference"])
        for indel in indels
    )

    max_count = max(
        indel["count"]
        for indel in aggregated_indels
    )

    # ------------------------------------------------------------
    # Plot.
    # ------------------------------------------------------------

    fig, ax = plt.subplots(figsize=(15, 7))

    # Insertions.
    if insertions:
        ax.scatter(
            [indel["position"] / 1000 for indel in insertions],
            [indel["length_difference"] for indel in insertions],
            s=[
                marker_size(indel["count"], base_size=55, increment=45)
                for indel in insertions
            ],
            color="#D55E00",
            edgecolor="black",
            linewidth=0.5,
            alpha=0.82,
            marker="^",
            label="Insertion",
            zorder=5,
        )

    # Deletions are represented as positive absolute lengths.
    if deletions:
        ax.scatter(
            [indel["position"] / 1000 for indel in deletions],
            [abs(indel["length_difference"]) for indel in deletions],
            s=[
                marker_size(indel["count"], base_size=55, increment=45)
                for indel in deletions
            ],
            color="#0072B2",
            edgecolor="black",
            linewidth=0.5,
            alpha=0.82,
            marker="v",
            label="Deletion",
            zorder=5,
        )

    # ------------------------------------------------------------
    # One shared gene track directly below the x-axis.
    # ------------------------------------------------------------

    gene_y = -max_indel_length * 0.13
    exon_height = max_indel_length * 0.045

    for gene_name, gene in genes.items():
        gene_start_kb = gene["start"] / 1000
        gene_end_kb = gene["end"] / 1000

        # Horizontal gene body.
        ax.hlines(
            y=gene_y,
            xmin=gene_start_kb,
            xmax=gene_end_kb,
            color="black",
            linewidth=1.3,
            zorder=2,
        )

        # Arrow indicates transcription direction.
        if gene["strand"] == "-":
            arrow_start = gene_end_kb
            arrow_end = gene_start_kb
        else:
            arrow_start = gene_start_kb
            arrow_end = gene_end_kb

        ax.add_patch(
            FancyArrowPatch(
                (arrow_start, gene_y),
                (arrow_end, gene_y),
                arrowstyle="-|>",
                mutation_scale=13,
                linewidth=1.4,
                color="black",
                zorder=2,
            )
        )

        # CDS exons.
        for cds in gene["cds"]:
            cds_start_kb = cds["start"] / 1000
            cds_width_kb = (cds["end"] - cds["start"] + 1) / 1000

            ax.add_patch(
                Rectangle(
                    (cds_start_kb, gene_y - exon_height / 2),
                    cds_width_kb,
                    exon_height,
                    facecolor="#009E73",
                    edgecolor="black",
                    linewidth=0.5,
                    zorder=3,
                )
            )

        # Gene name. Alternate label position above/below the shared track
        # only to improve readability if genes overlap.
        if gene["strand"] == "-":
            label_y = gene_y - exon_height * 1.5
            vertical_alignment = "top"
        else:
            label_y = gene_y + exon_height * 1.5
            vertical_alignment = "bottom"

        ax.text(
            (gene_start_kb + gene_end_kb) / 2,
            label_y,
            gene_name,
            ha="center",
            va=vertical_alignment,
            fontsize=9,
            fontweight="bold",
        )

    # ------------------------------------------------------------
    # Legend: variant type plus marker-size meaning.
    # ------------------------------------------------------------

    legend_handles = [
        plt.Line2D(
            [0],
            [0],
            marker="^",
            color="w",
            label="Insertion",
            markerfacecolor="#D55E00",
            markeredgecolor="black",
            markersize=9,
        ),
        plt.Line2D(
            [0],
            [0],
            marker="v",
            color="w",
            label="Deletion",
            markerfacecolor="#0072B2",
            markeredgecolor="black",
            markersize=9,
        ),
    ]

    # Add an explanatory marker-size legend only if duplicates occur.
    if max_count > 1:
        legend_handles.append(
            plt.Line2D(
                [0],
                [0],
                marker="o",
                color="w",
                label="Marker size = number of identical indels",
                markerfacecolor="#999999",
                markeredgecolor="black",
                markersize=8,
            )
        )

    ax.legend(
        handles=legend_handles,
        loc="upper right",
        frameon=True,
        fontsize=10,
    )

    # ------------------------------------------------------------
    # Layout.
    # ------------------------------------------------------------

    ax.axhline(0, color="black", linewidth=0.8)

    ax.set_xlim(0, args.region_length / 1000)

    ax.set_ylim(
        -max_indel_length * 0.34,
        max_indel_length * 1.18,
    )

    ax.set_xlabel(
        "Position in local reference region (kb)",
        fontsize=14,
    )

    ax.set_ylabel(
        "Variants length (bp)",
        fontsize=14,
    )

    ax.grid(axis="y", linestyle="--", alpha=0.40)
    ax.set_axisbelow(True)

    n_insertions = sum(
        1 for indel in indels
        if indel["variant_type"] == "INS"
    )

    n_deletions = sum(
        1 for indel in indels
        if indel["variant_type"] == "DEL"
    )

    ax.text(
        0.01,
        0.98,
        (
            f"Indels >= {args.min_indel_size} bp: {len(indels)}\n"
            f"Insertions: {n_insertions}\n"
            f"Deletions: {n_deletions}\n"
            f"Unique plotted positions/types: {len(aggregated_indels)}\n"
            f"Maximum identical indels: {max_count}\n"
            f"Annotated genes: {len(genes)}"
        ),
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=10,
        bbox={
            "boxstyle": "round,pad=0.4",
            "facecolor": "white",
            "edgecolor": "gray",
            "alpha": 0.90,
        },
    )

    plt.tight_layout()

    plt.savefig(
        f"{args.output_prefix}.png",
        dpi=300,
        bbox_inches="tight",
    )

    plt.savefig(
        f"{args.output_prefix}.pdf",
        bbox_inches="tight",
    )

    print(f"Raw indels >= {args.min_indel_size} bp: {len(indels)}")
    print(f"Unique position/type/length combinations: {len(aggregated_indels)}")
    print(f"Maximum identical indels at one location: {max_count}")
    print(f"Genes plotted: {len(genes)}")
    print(f"Output: {args.output_prefix}.png")
    print(f"Output: {args.output_prefix}.pdf")


if __name__ == "__main__":
    main()
